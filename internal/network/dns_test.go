package network

import (
	"os"
	"path/filepath"
	"testing"
)

func TestParseResolvConf(t *testing.T) {
	content := `# Generated by NetworkManager
nameserver 1.1.1.1
nameserver 8.8.8.8
search localdomain example.com
`
	tempDir := t.TempDir()
	resolvFile := filepath.Join(tempDir, "resolv.conf")
	if err := os.WriteFile(resolvFile, []byte(content), 0600); err != nil {
		t.Fatalf("failed to write fixture: %v", err)
	}

	cfg, err := parseResolvConf(resolvFile)
	if err != nil {
		t.Fatalf("unexpected error parsing resolv.conf: %v", err)
	}

	if len(cfg.Servers) != 2 {
		t.Fatalf("expected 2 nameservers, got %d", len(cfg.Servers))
	}
	if cfg.Servers[0] != "1.1.1.1" || cfg.Servers[1] != "8.8.8.8" {
		t.Errorf("unexpected nameservers: %v", cfg.Servers)
	}
	if len(cfg.SearchDomains) != 2 {
		t.Errorf("expected 2 search domains, got %d", len(cfg.SearchDomains))
	}
}

